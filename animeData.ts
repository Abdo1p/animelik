// Helper to get latest episodes across all series for the home page
export const getLatestEpisodes = () => {
  const result: { anime: Anime; episode: any; timeAgo: string }[] = [];
  const times = [
    'منذ 20 دقيقة',
    'منذ 45 دقيقة',
    'منذ ساعة',
    'منذ ساعتين',
    'منذ 3 ساعات',
    'منذ 5 ساعات',
    'منذ 7 ساعات',
    'منذ يوم',
    'منذ يومين',
    'منذ 3 أيام',
    'منذ 4 أيام',
    'منذ أسبوع',
  ];

  let timeIdx = 0;
  ANIME_DATABASE.forEach((anime) => {
    anime.seasons.forEach((season) => {
      const lastEps = [...season.episodes].reverse().slice(0, 2);
      lastEps.forEach((ep) => {
        result.push({
          anime,
          episode: ep,
          timeAgo: times[timeIdx % times.length],
        });
        timeIdx++;
      });
    });
  });

  return result.slice(0, 18);
};

